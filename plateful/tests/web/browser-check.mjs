import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

// Use an already installed Playwright module; this script installs nothing.
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.WEB_PREVIEW_URL || 'http://127.0.0.1:5173';
const output=fileURLToPath(new URL('../../apps/web/qa/',import.meta.url));
await mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[],external=[];
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(!request.url().startsWith(base)&&!request.url().startsWith('data:'))external.push(request.url());});
  await page.goto(base,{waitUntil:'networkidle'});
  assert.match(await page.title(),/Along/);
  assert.equal(await page.getByRole('button',{name:'Signups opening soon'}).isDisabled(),true);
  assert.equal(await page.locator('input[type="email"]').count(),0);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:`${output}desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.goto(`${base}/?demo=1`,{waitUntil:'networkidle'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:`${output}phone-checkin.png`,fullPage:true});
  assert.equal(await page.getByRole('button',{name:'Save my check-in'}).isDisabled(),true);
  assert.equal(await page.getByRole('textbox',{name:/Anything you’d like to remember/}).getAttribute('maxlength'),'500');
  await page.getByRole('button',{name:'bright',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Save my check-in'}).isDisabled(),true);
  await page.getByRole('button',{name:'low',exact:true}).click();
  await page.getByRole('checkbox',{name:/Moved my way/}).check();
  await page.getByRole('textbox',{name:/Anything you’d like to remember/}).fill('A short walk and a little time for myself.');
  await page.getByRole('button',{name:'Save my check-in'}).click();
  await page.getByText('3 of 3 explored',{exact:true}).waitFor();
  assert.equal(await page.locator('.journal-entry').count(),1);
  assert.match(await page.locator('.journal-entry').innerText(),/bright · appetite low/i);
  assert.match(await page.locator('.entry-note').innerText(),/A short walk/);
  await page.screenshot({path:`${output}phone-journey.png`,fullPage:true});
  await page.getByRole('button',{name:'Edit today'}).click();
  await page.getByRole('button',{name:'tough',exact:true}).click();
  await page.getByRole('button',{name:'Update today’s check-in'}).click();
  assert.equal(await page.locator('.journal-entry').count(),1);
  assert.match(await page.locator('.journal-entry').innerText(),/tough · appetite low/i);
  await page.getByRole('button',{name:'Reset the preview',exact:true}).click();
  await page.getByRole('button',{name:'Keep them',exact:true}).click();
  assert.equal(await page.locator('.journal-entry').count(),1);
  await page.getByRole('button',{name:'Reset the preview',exact:true}).click();
  await page.getByRole('button',{name:'Clear check-ins',exact:true}).click();
  await page.getByRole('button',{name:'My journey',exact:true}).click();
  await page.getByText('0 of 3 explored',{exact:true}).waitFor();
  assert.equal(await page.locator('.journal-entry').count(),0);
  assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0);
  await page.goto(base,{waitUntil:'networkidle'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:`${output}phone-landing.png`,fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  console.log('PASS: desktop/mobile layout, local check-in, journey, milestone accuracy, same-day edit, reset cancellation/confirmation, no storage, no external requests, disabled waitlist.');
  console.log(`Screenshots: ${output}`);
} finally {await browser.close();}
