import { APIError, json, requireLocalDemo } from './http.mjs';

export function anonymousSession(request, env) {
  requireLocalDemo(request, env);
  // An obviously fake marker for client plumbing, not an authentication token.
  return json({
    mode: 'demo', token: 'along-local-demo',
    user: { id: 'local-demo', isAnonymous: true },
    notice: 'Local preview. No account or server session was created.',
  }, 200, { 'set-auth-token': 'along-local-demo' });
}

export async function requireLiveSession(_request, _env) {
  // Activation seam: Better Auth anonymous + bearer + Apple plugins, D1 schema
  // generated by the installed official CLI, then auth.api.getSession(headers).
  // Never interpret a client user ID, fake demo marker or arbitrary bearer as identity.
  throw new APIError(503, 'auth_not_configured', 'Live sign-in is not configured.');
}
